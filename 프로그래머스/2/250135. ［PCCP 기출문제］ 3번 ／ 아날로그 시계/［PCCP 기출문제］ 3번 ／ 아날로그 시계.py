# 특정 시간 동안 초침이 시침/분침과 겹친 횟수
# 초침, 시침, 분침을 각각 0~1 사이의 수로 정규화한다. (소수점 세 자리 수까지)
# 초침 60칸 = 분침 1칸 = 시침 1/60칸
# 초침 3600칸 = 분침 60칸 = 시침 1칸
# 초침 1칸 = 분침 1/60칸 = 시침 1/3600칸

# 0시 5분 30초 = 총 5*60 + 30 = 330초
# 초침 30.000칸 % 60
# 분침 330/60 = 5.500칸 % 60
# 시침 330/3600 = 0.091칸 % 60
# 여기서 초침 기준 0.001초씩 더하며 초침과 분,시침이 겹치는 상황이 있는지 확인하기
# -> 근데 이건 내가 임의로 0.001초씩 자른거라서 정확한 수가 아니다

# 0:0:0부터 23:59:59까지 초침과 시침/분침이 겹치는 2852개 미리 구하기
# 그리고 그 중에서 찾기
# count(t): t초동안 초침과 시침/분침이 몇 번 겹치는지 구하는 함수

def solution(h1, m1, s1, h2, m2, s2):
    start = h1 * 3600 + m1 * 60 + s1
    end = h2 * 3600 + m2 * 60 + s2

    # 00:00:00은 제외하고,
    # 0초 초과 t초 이하에서 알람이 울린 횟수
    def count_until(t):
        # 초침과 분침이 다시 겹치는 주기
        # 상대속도: 1/60 - 1/3600 = 59/3600바퀴/초
        # t초 동안 겹친 횟수 = floor(t * 59 / 3600)
        second_minute = t * 59 // 3600

        # 초침과 시침이 다시 겹치는 주기
        # 상대속도: 1/60 - 1/43200 = 719/43200바퀴/초
        # t초 동안 겹친 횟수 = floor(t * 719 / 43200)
        second_hour = t * 719 // 43200

        count = second_minute + second_hour

        # 12:00:00에는 초침, 분침, 시침이 모두 겹친다.
        # 위에서 초침-분침 1번, 초침-시침 1번으로 총 2번 세었으므로
        # 실제 알람 1번이 되도록 중복된 1번을 뺀다.
        if t >= 12 * 3600:
            count -= 1

        return count

    # 시작 시각에 알람이 울리는지 확인
    def is_alarm_time(h, m, s):
        h %= 12

        # 원래 각도 계산식
        #
        # 초침 각도 = s × 6
        # 분침 각도 = m × 6 + s × 0.1
        # 시침 각도 = h × 30 + m × 0.5 + s ÷ 120
        #
        # 하지만 0.1, 0.5, 1/120 같은 실수로 == 비교를 하면
        # 부동소수점 오차가 발생할 수 있다.
        #
        # 따라서 모든 각도에 120을 곱해서 정수로 바꾼다.

        # 초침:
        # (s × 6) × 120
        # = s × 720
        second_angle_x120 = s * 720

        # 분침:
        # (m × 6 + s × 0.1) × 120
        # = m × 720 + s × 12
        minute_angle_x120 = m * 720 + s * 12

        # 시침:
        # (h × 30 + m × 0.5 + s ÷ 120) × 120
        # = h × 3600 + m × 60 + s
        hour_angle_x120 = h * 3600 + m * 60 + s

        # 120을 곱한 값이 같다는 것은
        # 원래 각도도 같다는 뜻이다.
        return (
            second_angle_x120 == minute_angle_x120
            or second_angle_x120 == hour_angle_x120
        )

    # count_until(end) - count_until(start)는
    # 시작 시각을 제외하고 종료 시각을 포함한 (start, end]의 횟수
    answer = count_until(end) - count_until(start)

    # 문제에서는 시작 시각도 포함하므로,
    # 시작 순간에 알람이 울린다면 1번 더한다.
    if is_alarm_time(h1, m1, s1):
        answer += 1

    return answer