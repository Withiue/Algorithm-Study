def solution(n):
    # dp[i] = i칸까지 가는 방법의 수
    dp = [0] * (n + 1)

    # 0칸에 도착하는 방법은 1가지라고 둠
    # 아무것도 하지 않는 경우
    dp[0] = 1

    # 1칸은 1칸 점프 한 번밖에 없음
    if n >= 1:
        dp[1] = 1

    # 2칸부터 계산
    for i in range(2, n + 1):

        # i칸에 도착하는 방법은
        # 1. i-1칸에서 1칸 점프해서 오는 경우
        # 2. i-2칸에서 2칸 점프해서 오는 경우
        #
        # 따라서 두 경우의 수를 더함
        dp[i] = (dp[i - 1] + dp[i - 2]) % 1234567

    return dp[n]